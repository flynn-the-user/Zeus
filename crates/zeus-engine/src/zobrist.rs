//! Zobrist position hashing, per `Reference/search/Zobrist_Hashing.md`.
//! Recomputes the full hash from scratch each call rather than updating
//! incrementally — a deliberate simplification documented in that file.
use chess::{Board, ALL_COLORS, ALL_PIECES, ALL_SQUARES};
use std::sync::LazyLock;

const NUM_PIECE_SQUARE: usize = 12 * 64;
const NUM_CASTLING: usize = 4;
const NUM_EN_PASSANT: usize = 8;

struct ZobristTable {
    piece_square: [u64; NUM_PIECE_SQUARE],
    side_to_move: u64,
    castling: [u64; NUM_CASTLING],
    en_passant_file: [u64; NUM_EN_PASSANT],
}

/// splitmix64 (Zeus's own choice of generator/seed - see
/// Reference/search/Zobrist_Hashing.md, which only requires the 781
/// numbers be well-distributed, not generated by any particular PRNG).
struct SplitMix64(u64);

impl SplitMix64 {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E3779B97F4A7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58476D1CE4E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D049BB133111EB);
        z ^ (z >> 31)
    }
}

static TABLE: LazyLock<ZobristTable> = LazyLock::new(|| {
    let mut rng = SplitMix64(0x5EED_5EED_5EED_5EEDu64); // fixed seed: reproducible hashes run-to-run
    let mut piece_square = [0u64; NUM_PIECE_SQUARE];
    for v in piece_square.iter_mut() {
        *v = rng.next();
    }
    let mut castling = [0u64; NUM_CASTLING];
    for v in castling.iter_mut() {
        *v = rng.next();
    }
    let mut en_passant_file = [0u64; NUM_EN_PASSANT];
    for v in en_passant_file.iter_mut() {
        *v = rng.next();
    }
    ZobristTable {
        piece_square,
        side_to_move: rng.next(),
        castling,
        en_passant_file,
    }
});

/// Computes `board`'s Zobrist key: XOR of the random number for every
/// piece-on-square, the four castling rights, the en passant file (if
/// any), and side-to-move — per
/// `Reference/search/Zobrist_Hashing.md`'s 781-number scheme.
pub fn hash(board: &Board) -> u64 {
    let t = &*TABLE;
    let mut h = 0u64;

    for &sq in ALL_SQUARES.iter() {
        if let (Some(piece), Some(color)) = (board.piece_on(sq), board.color_on(sq)) {
            let idx = color.to_index() * 6 * 64 + piece.to_index() * 64 + sq.to_index();
            h ^= t.piece_square[idx];
        }
    }

    if board.side_to_move() == chess::Color::Black {
        h ^= t.side_to_move;
    }

    for (i, &color) in ALL_COLORS.iter().enumerate() {
        let rights = board.castle_rights(color);
        if rights.has_kingside() {
            h ^= t.castling[i * 2];
        }
        if rights.has_queenside() {
            h ^= t.castling[i * 2 + 1];
        }
    }

    if let Some(ep_square) = board.en_passant() {
        h ^= t.en_passant_file[ep_square.get_file().to_index()];
    }

    h
}

#[allow(dead_code)]
const _ASSERT_PIECE_COUNT: () = assert!(ALL_PIECES.len() == 6);
